// Cached fixtures (loaded once)
static FIXTURES: std::sync::OnceLock<RecordedFixtures> = std::sync::OnceLock::new();

fn get_fixtures() -> &'static RecordedFixtures {
    FIXTURES.get_or_init(load_fixtures)
}

/// Get fixture suggestion cards
pub fn fixture_suggestion_cards() -> Vec<SuggestionCard> {
    get_fixtures()
        .cards
        .iter()
        .map(|c| SuggestionCard {
            id: c.id,
            title: c.title.clone(),
            category: c.category.clone(),
            description: c.description.clone(),
            command: None,
            selected: c.selected,
            streaming: false,
        })
        .collect()
}

/// Fixture tool log entries
pub fn fixture_tool_log() -> Vec<String> {
    get_fixtures().tool_log.clone()
}

/// Fixture thought log entries
pub fn fixture_thought_log() -> Vec<String> {
    get_fixtures().thought_log.clone()
}

/// Fixture analysis log entries
pub fn fixture_analysis_log() -> Vec<String> {
    get_fixtures().analysis_log.clone()
}

/// Fixture projects for project chooser
pub fn fixture_projects() -> Vec<FixtureProject> {
    // Return static references by leaking the strings
    // This is fine since fixtures are loaded once and live forever
    get_fixtures()
        .projects
        .iter()
        .map(|p| {
            let name: &'static str = Box::leak(p.name.clone().into_boxed_str());
            let path: &'static str = Box::leak(p.path.clone().into_boxed_str());
            let languages: &'static [&'static str] = Box::leak(
                p.languages
                    .iter()
                    .map(|l| -> &'static str { Box::leak(l.clone().into_boxed_str()) })
                    .collect::<Vec<_>>()
                    .into_boxed_slice(),
            );
            FixtureProject { name, path, languages }
        })
        .collect()
}

/// Panel fixture enum for type-safe access
pub enum PanelFixture {
    QuestLog(Vec<SuggestionCard>),
    Execution {
        tool_log: Vec<String>,
        thought_log: Vec<String>,
    },
    Analysis(Vec<String>),
    ProjectChooser(Vec<FixtureProject>),
}

/// Get fixture data for a specific panel type
pub fn get_panel_fixture(panel_type: &str) -> Option<PanelFixture> {
    match panel_type {
        "quest_log" => Some(PanelFixture::QuestLog(fixture_suggestion_cards())),
        "execution" => Some(PanelFixture::Execution {
            tool_log: fixture_tool_log(),
            thought_log: fixture_thought_log(),
        }),
        "analysis" => Some(PanelFixture::Analysis(fixture_analysis_log())),
        "project_chooser" => Some(PanelFixture::ProjectChooser(fixture_projects())),
        _ => None,
    }
}

/// Capture session data for fixtures (called during recording)
#[derive(Debug, Default)]
pub struct FixtureCapture {
    pub cards: Vec<RecordedCard>,
    pub tool_log: Vec<String>,
    pub thought_log: Vec<String>,
    pub analysis_log: Vec<String>,
}

impl FixtureCapture {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn add_card(&mut self, card: &SuggestionCard) {
        self.cards.push(RecordedCard {
            id: card.id,
            title: card.title.clone(),
            category: card.category.clone(),
            description: card.description.clone(),
            selected: card.selected,
        });
    }

    pub fn add_tool(&mut self, entry: String) {
        self.tool_log.push(entry);
    }

    pub fn add_thought(&mut self, entry: String) {
        self.thought_log.push(entry);
    }

    pub fn add_analysis(&mut self, entry: String) {
        self.analysis_log.push(entry);
    }

    /// Export captured data to JSON
    pub fn export(&self, project_name: &str) -> Result<String, serde_json::Error> {
        use std::time::{SystemTime, UNIX_EPOCH};
        let timestamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|d| d.as_secs())
            .unwrap_or(0);

        let fixtures = RecordedFixtures {
            version: 1,
            recorded_at: format!("{}", timestamp), // Unix timestamp, convert to ISO 8601 externally if needed
            project_name: project_name.to_string(),
            cards: self.cards.clone(),
            tool_log: self.tool_log.clone(),
            thought_log: self.thought_log.clone(),
            analysis_log: self.analysis_log.clone(),
            projects: vec![], // Projects are discovered, not captured
        };
        serde_json::to_string_pretty(&fixtures)
    }

    /// Save captured data to file
    pub fn save(&self, project_name: &str, path: &str) -> Result<(), Box<dyn std::error::Error>> {
        let json = self.export(project_name)?;
        std::fs::create_dir_all(std::path::Path::new(path).parent().unwrap_or(std::path::Path::new(".")))?;
        std::fs::write(path, json)?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_fixture_cards_not_empty() {
        let cards = fixture_suggestion_cards();
        assert!(!cards.is_empty());
        assert!(cards.len() >= 4);
    }

    #[test]
    fn test_fixture_logs_not_empty() {
        assert!(!fixture_tool_log().is_empty());
        assert!(!fixture_thought_log().is_empty());
        assert!(!fixture_analysis_log().is_empty());
    }

    #[test]
    fn test_get_panel_fixture() {
        assert!(get_panel_fixture("quest_log").is_some());
        assert!(get_panel_fixture("execution").is_some());
        assert!(get_panel_fixture("analysis").is_some());
        assert!(get_panel_fixture("project_chooser").is_some());
        assert!(get_panel_fixture("invalid").is_none());
    }

    #[test]
    fn test_fixture_capture() {
        let mut capture = FixtureCapture::new();
        capture.add_tool("[00:00:00] Test".to_string());
        capture.add_thought("Thinking...".to_string());

        let json = capture.export("test-project").unwrap();
        assert!(json.contains("test-project"));
        assert!(json.contains("Test"));
    }
}
