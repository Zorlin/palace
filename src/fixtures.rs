//! Fixture data for panel previews
//!
//! Contains recorded data from real Palace sessions, used to render
//! realistic previews in the panel chooser dialog (Android ICS style).
//!
//! ## How fixtures are generated:
//!
//! 1. Run `palace capture-fixtures` to record a real AI session
//! 2. Session data is saved to `fixtures/session.json`
//! 3. Build process embeds this data via `include_str!`
//! 4. CI pipeline regenerates fixtures when UI changes
//!
//! The default fixture is an "Asteroids" implementation session.

use crate::state::SuggestionCard;
use serde::{Deserialize, Serialize};

/// Recorded fixture data from a real session
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RecordedFixtures {
    /// Version of the fixture format
    pub version: u32,
    /// When these fixtures were recorded (ISO 8601)
    pub recorded_at: String,
    /// Project name that was used
    pub project_name: String,
    /// Example suggestion cards
    pub cards: Vec<RecordedCard>,
    /// Tool log entries (timestamped)
    pub tool_log: Vec<String>,
    /// Thought log entries
    pub thought_log: Vec<String>,
    /// Analysis log entries
    pub analysis_log: Vec<String>,
    /// Example projects (for project chooser preview)
    pub projects: Vec<RecordedProject>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RecordedCard {
    pub id: usize,
    pub title: String,
    pub category: String,
    pub description: String,
    pub selected: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RecordedProject {
    pub name: String,
    pub path: String,
    pub languages: Vec<String>,
}

/// Example project for fixtures (legacy format, kept for compatibility)
pub struct FixtureProject {
    pub name: &'static str,
    pub path: &'static str,
    pub languages: &'static [&'static str],
}

// Embedded fixture data - generated by `palace capture-fixtures`
// If the file doesn't exist, we fall back to default inline data
const FIXTURE_JSON: Option<&str> = option_env!("PALACE_FIXTURES_JSON");

/// Load fixtures from embedded JSON or fall back to defaults
fn load_fixtures() -> RecordedFixtures {
    // Try to load from embedded JSON (set at build time)
    if let Some(json) = FIXTURE_JSON {
        if let Ok(fixtures) = serde_json::from_str(json) {
            return fixtures;
        }
    }

    // Try to load from file at runtime (for development)
    if let Ok(json) = std::fs::read_to_string("fixtures/session.json") {
        if let Ok(fixtures) = serde_json::from_str(&json) {
            return fixtures;
        }
    }

    // Fall back to default inline fixtures
    default_fixtures()
}

