#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generator_start_state() {
        let gen = ScenarioGenerator::new();
        assert!(matches!(
            gen.current_state(),
            GeneratorState::Start { selected: 0 }
        ));
    }

    #[test]
    fn test_navigation() {
        let mut gen = ScenarioGenerator::new();

        gen.navigate(1);
        if let GeneratorState::Start { selected } = gen.current_state() {
            assert_eq!(*selected, 1);
        } else {
            panic!("Expected Start state");
        }

        gen.navigate(-1);
        if let GeneratorState::Start { selected } = gen.current_state() {
            assert_eq!(*selected, 0);
        }
    }

    #[test]
    fn test_from_description() {
        let gen = ScenarioGenerator::from_description("implement asteroids".into());
        assert!(matches!(
            gen.current_state(),
            GeneratorState::Enriching { .. }
        ));
    }

    #[test]
    fn test_build_scenario() {
        let gen = ScenarioGenerator::new();
        let enriched = EnrichedDescription {
            enriched_description: "Build an asteroids game in Rust with WGPU.".into(),
            inferred_goals: vec!["Working game".into(), "Ship controls".into()],
            likely_project_type: "rust".into(),
            suggested_permissions: vec![PermissionType::Read, PermissionType::Write, PermissionType::Cargo],
        };

        let scenario = gen.build_scenario(&[], Some(&enriched));
        assert_eq!(scenario.goals.len(), 2);
        assert!(scenario.permissions.is_some());
    }
}
